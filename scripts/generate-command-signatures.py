#!/usr/bin/env python3
"""Project the typed command schema into the ledger's literal Rust inventory."""

import argparse
import json
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "crates/rmux-core/src/command_schema.rs"
OUTPUT = ROOT / "crates/rmux-core/src/command_inventory/signatures.rs"
STRING = r'"(?:[^"\\]|\\.)*"'
ROW = re.compile(
    rf'\s*\(({STRING}),\s*(?:None|Some\({STRING}\)),\s*(tmux|extension),\s*'
    rf'(\d+),\s*({STRING}),\s*\w+(?:\(\w*\),\s*\w+,\s*\[[\w :]*\])?\);'
)


def render():
    source = SCHEMA.read_text(encoding="utf-8")
    rows = []
    for start, end in [("commands {", "delegated {"), ("delegated {", "local {")]:
        body = source.split(start, 1)[1].split(end, 1)[0].rstrip().removesuffix("}")
        position = 0
        while body[position:].strip():
            match = ROW.match(body, position)
            if match is None:
                raise ValueError(f"unsupported command schema row: {body[position:position + 100]!r}")
            name, kind, order, usage = match.groups()
            rows.append((kind == "extension", int(order), json.loads(name), json.loads(usage)))
            position = match.end()
    for extension in (False, True):
        orders = sorted(order for kind, order, _, _ in rows if kind == extension)
        if orders != list(range(len(orders))):
            raise ValueError("schema inventory order must be contiguous and unique")
    header = '''//! Generated by scripts/generate-command-signatures.py; edit command_schema.rs.
//! The command inventory verifies this projection against the schema at compile time.

pub(super) fn list_command_usage(name: &str) -> &'static str {
    LIST_COMMAND_SIGNATURES
        .iter()
        .find_map(|(command_name, usage)| (*command_name == name).then_some(*usage))
        .unwrap_or("")
}

pub(super) const LIST_COMMAND_SIGNATURES: &[(&str, &str)] = &[
'''
    entries = ''
    for _, _, name, usage in sorted(rows):
        name, usage = json.dumps(name), json.dumps(usage)
        compact = f'    ({name}, {usage}),\n'
        entries += compact if len(compact) <= 90 else f'    (\n        {name},\n        {usage},\n    ),\n'
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        cwd=ROOT, input=header + entries + "];\n", text=True, capture_output=True,
        check=True,
    ).stdout


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="update the generated projection")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_text(expected, encoding="utf-8")
    elif OUTPUT.read_text(encoding="utf-8") != expected:
        parser.error("stale command signatures; run with --write")
