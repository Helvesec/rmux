#!/usr/bin/env python3
"""Regenerate crates/rmux-core/src/command_parser/argument_check/templates.rs.

Usage: probe-tmux-argument-templates.py TMUX SOCKET WORKDIR > templates.rs

Starts a tmux server on the private SOCKET and derives each command's
args_parse template (boolean flags, value flags, positional bounds) by parsing
one-line files with `source-file -n`, which parses and never executes.
"""
import os
import re
import string
import subprocess
import sys

ENV = {k: v for k, v in os.environ.items() if k not in ("TMUX", "TMUX_PANE", "RMUX", "RMUX_PANE")}
# Bound by main(): importing this module must not start or stop a tmux server.
TMUX = SOCKET = CONF = None


def tmux(*args):
    return subprocess.run([TMUX, "-S", SOCKET, "-f", "/dev/null", *args],
                          capture_output=True, text=True, env=ENV, timeout=10)


def cause(line):
    with open(CONF, "w") as conf:
        conf.write(line + "\n")
    out = (lambda p: (p.stdout + p.stderr).strip())(tmux("source-file", "-n", CONF))
    return out.split(": ", 1)[1] if out.startswith(CONF + ":") else out


def bound(name, line, kind):
    match = re.fullmatch(rf"command {re.escape(name)}: too {kind} arguments "
                         rf"\(need at (?:least|most) (\d+)\)", cause(line))
    return int(match.group(1)) if match else None


def template(name):
    boolean, value = "", ""
    for flag in string.ascii_letters + string.digits:
        first = cause(f"{name} -{flag}")
        if first == f"command {name}: unknown flag -{flag}":
            continue
        if first == f"command {name}: -{flag} expects an argument":
            value += flag
        elif cause(f"{name} -{flag}:") == f"command {name}: invalid flag -:":
            boolean += flag
        else:
            sys.exit(f"{name} -{flag}: optional-value flags are not modelled")
    lower = bound(name, name, "few") or 0
    upper = bound(name, name + " x" * 300, "many")
    return boolean, value, lower, "None" if upper is None else f"Some({upper})"


def main(argv):
    global TMUX, SOCKET, CONF
    if len(argv) != 4:
        sys.exit("usage: probe-tmux-argument-templates.py TMUX SOCKET WORKDIR")
    TMUX, SOCKET, workdir = argv[1:4]
    os.makedirs(workdir, exist_ok=True)
    CONF = os.path.join(workdir, "probe.conf")
    tmux("new-session", "-d", "-s", "probe")
    try:
        names = sorted(tmux("list-commands", "-F", "#{command_list_name}").stdout.split())
        print("//! Generated by scripts/probe-tmux-argument-templates.py from tmux 3.7b.")
        print("//! Each row is what tmux's `args_parse` accepts for one command: boolean")
        print("//! flags, value flags, and the positional argument bounds.")
        print()
        print("use super::TmuxArgumentTemplate;")
        print()
        print("pub(super) const TMUX_ARGUMENT_TEMPLATES: &[TmuxArgumentTemplate] = &[")
        for name in names:
            boolean, value, lower, upper = template(name)
            print(f'    TmuxArgumentTemplate::new("{name}", "{boolean}", "{value}", {lower}, {upper}),')
        print("];")
    finally:
        tmux("kill-server")


if __name__ == "__main__":
    main(sys.argv)
