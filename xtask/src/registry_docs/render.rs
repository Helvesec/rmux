//! Deterministic text projections from a single implemented snapshot.

use super::ledger::Ledger;
use super::snapshot::{Command, Snapshot};
use super::{Artifact, Error};

const MARKDOWN_MARKER: &str = "<!-- Generated by xtask registry-docs; do not edit. -->\n";
const MAN_MARKER: &str = ".\\\" Generated by xtask registry-docs; do not edit.\n";
const JSON_MARKER: &str = "{\n  \"generator\": \"xtask registry-docs\",";

pub(super) fn artifacts(snapshot: &Snapshot, ledger: &Ledger) -> Result<Vec<Artifact>, Error> {
    // Struct order keeps the ownership marker stable without JSON map feature assumptions.
    #[derive(serde::Serialize)]
    struct Report<'a> {
        generator: &'static str,
        schema: u32,
        scope: &'static str,
        registry: &'a Snapshot,
        divergences: &'a Ledger,
    }
    let json = serde_json::to_string_pretty(&Report {
        generator: "xtask registry-docs",
        schema: 1,
        scope: "implemented registries and declared divergences; evidence is not executed",
        registry: snapshot,
        divergences: ledger,
    })
    .map_err(|error| Error::Invalid(format!("cannot render compliance report: {error}")))?
        + "\n";
    Ok(vec![
        Artifact {
            name: "cli-reference.md",
            content: cli(snapshot),
            marker: MARKDOWN_MARKER,
        },
        Artifact {
            name: "configuration-reference.md",
            content: configuration(snapshot),
            marker: MARKDOWN_MARKER,
        },
        Artifact {
            name: "rmux.1",
            content: man(snapshot),
            marker: MAN_MARKER,
        },
        Artifact {
            name: "compliance.md",
            content: compliance(snapshot, ledger),
            marker: MARKDOWN_MARKER,
        },
        Artifact {
            name: "compliance.json",
            content: json,
            marker: JSON_MARKER,
        },
    ])
}

fn cli(snapshot: &Snapshot) -> String {
    let mut output = format!(
        "{MARKDOWN_MARKER}# RMUX {} CLI reference\n\n",
        snapshot.version
    );
    output
        .push_str("Top-level options and command help are projected from the implemented CLI.\n\n");
    code(&mut output, &snapshot.top_level_help);
    for command in &snapshot.commands {
        output.push_str(&format!("\n## `{}`\n\n", command.name));
        if let Some(alias) = &command.alias {
            output.push_str(&format!("Alias: `{alias}`.\n\n"));
        }
        code(&mut output, &command.help);
    }
    output.push_str("\n# Built-in command aliases\n\n");
    for alias in &snapshot.cli_aliases {
        output.push_str(&format!("- `{}` → `{}`\n", alias.name, alias.expansion));
    }
    output.push_str("\n# Local CLI commands\n");
    for command in &snapshot.local_commands {
        output.push_str(&format!("\n### `{}`\n\n", command.name));
        code(&mut output, &command.help);
    }
    output
}

fn code(output: &mut String, text: &str) {
    // Defaults and CLI help may contain fences; use a longer fence than the input.
    let fence = "`".repeat(
        text.split(|c| c != '`')
            .map(str::len)
            .max()
            .unwrap_or(0)
            .max(2)
            + 1,
    );
    output.push_str(&format!("{fence}text\n{text}"));
    if !text.ends_with('\n') {
        output.push('\n');
    }
    output.push_str(&format!("{fence}\n"));
}

fn configuration(snapshot: &Snapshot) -> String {
    let mut output = format!("{MARKDOWN_MARKER}# RMUX configuration reference\n\nDefaults below come from the {} registry compiled into this generator.\n\n", snapshot.defaults_platform);
    output.push_str("Option declarations describe accepted configuration values; they do not claim that deferred runtime effects are implemented.\n\n");
    for option in &snapshot.options {
        output.push_str(&format!(
            "## `{}`\n\nType: {}. Scopes: {}. Global root: {}. Array: {}.\n\n",
            option.name,
            option.value_type,
            option.scopes.join(", "),
            option.global_root,
            option.array
        ));
        if !option.aliases.is_empty() {
            output.push_str(&format!("Aliases: {}.\n\n", option.aliases.join(", ")));
        }
        if option.array {
            output.push_str(&format!("Separator: `{}`.\n\n", option.separator));
        }
        output.push_str("Default value (array entries are shown individually):\n\n");
        for (default, platform) in option.defaults.iter().zip(&option.default_platforms) {
            output.push_str(&format!("Platform: {platform}.\n\n"));
            code(&mut output, default);
        }
    }
    output
}

fn man(snapshot: &Snapshot) -> String {
    let mut output = format!("{MAN_MARKER}.TH RMUX 1 \"\" \"RMUX {}\" \"RMUX Registry Reference\"\n.SH NAME\nrmux \\- terminal multiplexer command reference\n.SH SYNOPSIS\n.nf\n", snapshot.version);
    output.push_str(&troff(&snapshot.top_level_help));
    output.push_str(".fi\n.SH IMPLEMENTED COMMAND SURFACE\n");
    output.push_str(&format!(
        "The public CLI dispatches {} commands:\n.nf\n",
        snapshot.commands.len()
    ));
    for command in &snapshot.commands {
        output.push_str(&command.name);
        if let Some(alias) = &command.alias {
            output.push_str(&format!(" ({alias})"));
        }
        output.push('\n');
    }
    output.push_str(".fi\n.SH BUILT-IN COMMAND ALIASES\n.nf\n");
    for alias in &snapshot.cli_aliases {
        output.push_str(&troff(&format!("{} => {}", alias.name, alias.expansion)));
    }
    output.push_str(".fi\n.SH COMMAND REFERENCE\n");
    for command in &snapshot.commands {
        man_command(&mut output, command);
    }
    output.push_str(".SH LOCAL CLI COMMANDS\n");
    for command in &snapshot.local_commands {
        man_command(&mut output, command);
    }
    output.push_str(".SH CONFIGURATION\n");
    output.push_str(&troff(&format!("Default values are from the {} registry. Declarations do not certify deferred runtime effects.", snapshot.defaults_platform)));
    for option in &snapshot.options {
        output.push_str(&format!(".SS {}\n.nf\n", option.name));
        output.push_str(&troff(&format!("Type: {}\nScopes: {}\nGlobal root: {}\nAliases: {}\nArray: {}\nSeparator: {}\nDefaults:\n{}",
            option.value_type, option.scopes.join(", "), option.global_root, option.aliases.join(", "), option.array, option.separator,
            option.defaults.iter().zip(&option.default_platforms).map(|(value, platform)| format!("{platform}: {value}")).collect::<Vec<_>>().join("\n"))));
        output.push_str(".fi\n");
    }
    output.push_str(super::manual_context::TEXT);
    output.push_str("In short-option clusters,\n.B -V\nstops the\n.B -h\nscan, so\n.B -Vh\nprints the version.\n.PP\nCommand help uses\n.BR \"rmux <command> --help\" .\nShort\n.B -h\nremains available for tmux command semantics such as\n.BR \"rmux split-window -h\" .\n");
    output.push_str("\n.SH EXPERIMENTAL KITTY KEYBOARD\nKitty Keyboard is disabled by default and full protocol support is not qualified.\nThe default build ignores its negotiation and retains legacy and xterm extended keys.\nKitty graphics is independent. To opt in, build with\n.B cargo build --release --features kitty-keyboard\nand restart the daemon using that binary. Applications may then negotiate enhancement flags.\n");
    output
}

fn man_command(output: &mut String, command: &Command) {
    output.push_str(&format!(".SS {}\n.nf\n", command.name));
    output.push_str(&troff(&command.help));
    output.push_str(".fi\n");
}

fn troff(text: &str) -> String {
    let mut output = String::new();
    for line in text.lines() {
        if line.starts_with(['.', '\'']) {
            output.push_str("\\&");
        }
        output.push_str(&line.replace('\\', "\\e").replace('-', "\\-"));
        // Keep significant trailing spaces without whitespace at the source line end.
        if line.ends_with(char::is_whitespace) {
            output.push_str("\\&");
        }
        output.push('\n');
    }
    output
}

fn cell(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "&#124;")
        .replace('\n', "<br>")
}

fn compliance(snapshot: &Snapshot, ledger: &Ledger) -> String {
    let mut output = format!("{MARKDOWN_MARKER}# RMUX registry compliance projection\n\nSource: `tests/reference/tmux_compat/divergences.toml` (schema {}).\n\nOracle policy: {}. Unlisted divergences are bugs: {}.\n\nImplemented command declarations: {}. Configuration declarations: {}. Defaults platform: {}.\n\nThis report projects registered declarations and evidence references. It does not execute tests or certify native behavior or compatibility.\n\n",
        ledger.schema, cell(&ledger.policy.oracle), ledger.policy.unlisted_divergences_are_bugs,
        snapshot.commands.len(), snapshot.options.len(), snapshot.defaults_platform);
    output.push_str("Historical evidence records declared provenance only; its availability and contents are not verified. Current source references and test symbols are checked in this checkout.\n\n");
    output.push_str("| ID | Declared divergence | Inventory | Current source evidence/tests | Retired by | Historical evidence (declared only) | Deferred | Limitations |\n| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");
    for entry in &ledger.entry {
        let evidence = entry
            .evidence
            .iter()
            .chain(&entry.tests)
            .map(|s| cell(s))
            .collect::<Vec<_>>()
            .join("<br>");
        output.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {} | {} |\n",
            cell(&entry.id),
            cell(&entry.summary),
            cell(&entry.inventory),
            evidence,
            cell(entry.retired_by.as_deref().unwrap_or("")),
            entry
                .historical_evidence
                .iter()
                .map(|s| cell(s))
                .collect::<Vec<_>>()
                .join("<br>"),
            entry
                .deferred
                .iter()
                .map(|s| cell(s))
                .collect::<Vec<_>>()
                .join("<br>"),
            entry
                .limitations
                .iter()
                .map(|s| cell(s))
                .collect::<Vec<_>>()
                .join("<br>")
        ));
    }
    output
}
