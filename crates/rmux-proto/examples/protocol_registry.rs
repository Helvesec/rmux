//! Print the reference generated from the capability and error registries.
use rmux_proto::capabilities::CAPABILITY_REGISTRY;
use rmux_proto::error::ERROR_REGISTRY;

fn main() {
    println!("# Protocol capability and error reference\n");
    println!("Generated by `cargo run -p rmux-proto --example protocol_registry`.\n");
    println!("Capabilities are matched by exact id. Each caller chooses Required or Optional:");
    println!("a missing Required id returns UnsupportedCapability, even when a fallback exists.");
    println!("Optional absence returns the registered fallback or Unavailable; the caller decides");
    println!("whether to use that fallback. Unknown advertised ids are Available; unknown absent");
    println!(
        "ids are Unavailable when optional and errors when required. No fallback is automatic.\n"
    );
    println!(
        "Advertisement is build-dependent: Baseline is always included, Web only with browser"
    );
    println!(
        "sharing enabled, and Retired never. Registry order preserves the published inventory."
    );
    println!(
        "Advertised negotiation needs no extra opt-in; RequiredOnConnection needs an explicit"
    );
    println!("handshake on that connection; RequiredPerRequest uses an embedded handshake;");
    println!("AttachOptIn echoes the id in the attach request. Lifetime describes negotiated");
    println!("permission, not resource TTL. Cached inventories are discarded on reconnect.\n");
    println!("| Capability | Advertiser | Direction | Scope | Lifetime | Negotiation | Optional fallback | Advertisement |");
    println!("|---|---|---|---|---|---|---|---|");
    for entry in CAPABILITY_REGISTRY {
        println!(
            "| `{}` | {:?} | {:?} | {:?} | {:?} | {:?} | {:?} | {:?} |",
            entry.id,
            entry.advertiser,
            entry.direction,
            entry.scope,
            entry.lifetime,
            entry.negotiation,
            entry.fallback,
            entry.advertisement,
        );
    }
    println!(
        "\nError codes are local, payload-free projections of RmuxError. They add no wire fields."
    );
    println!("The numeric column is the existing bincode discriminant; descriptions come from");
    println!(
        "the same definitions as the serialized variants. Error display messages are unchanged.\n"
    );
    println!("| Code | Bincode discriminant | Meaning |");
    println!("|---|---|---|");
    for entry in ERROR_REGISTRY {
        println!(
            "| `{}` | {} | {} |",
            entry.code.as_str(),
            entry.code.wire_discriminant(),
            entry.description.trim()
        );
    }
}
